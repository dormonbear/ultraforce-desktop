export type Locale = "en" | "zh-CN";
export type MessageKey = keyof typeof chinese;

export function resolveLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const base = language.toLowerCase().split(/[-_]/)[0];
    if (base === "zh") return "zh-CN";
    if (base === "en") return "en";
  }
  return "en";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const message = locale === "zh-CN" ? chinese[key] : key;
  return formatMessage(message, values);
}

export function browserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const languages = navigator.languages;
  if (Array.isArray(languages) && languages.length) return resolveLocale(languages);
  return resolveLocale(typeof navigator.language === "string" ? [navigator.language] : []);
}

function subscribe(callback: () => void) {
  window.addEventListener("languagechange", callback);
  return () => window.removeEventListener("languagechange", callback);
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribe, browserLocale, () => "en" as Locale);
  const t = useCallback(
    (key: MessageKey, values?: Readonly<Record<string, string | number>>) =>
      translate(locale, key, values),
    [locale],
  );
  return { locale, t };
}
