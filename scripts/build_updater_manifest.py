"""Build one complete updater manifest after all uploads. / 所有上传结束后生成一份完整更新清单。"""

import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import sys


REPOSITORY = "dormonbear/ultraforce-desktop"


def build_manifest(metadata: dict, signatures: Path) -> dict:
    tag = metadata["tag_name"]
    if not re.fullmatch(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", tag):
        raise ValueError("Invalid release tag / 无效的发布标签")
    if metadata.get("draft") or metadata.get("prerelease"):
        raise ValueError("Expected stable release / 需要稳定发布")
    version = tag[1:]
    names = [asset["name"] for asset in metadata["assets"]]
    if len(names) != len(set(names)):
        raise ValueError("Duplicate release assets / 发布产物名称重复")
    assets = {asset["name"]: asset for asset in metadata["assets"]}
    platforms = {}
    bundles = {
        "Ultraforce_aarch64.app.tar.gz": ["darwin-aarch64", "darwin-aarch64-app"],
        "Ultraforce_x64.app.tar.gz": ["darwin-x86_64", "darwin-x86_64-app"],
        f"Ultraforce_{version}_amd64.AppImage": ["linux-x86_64", "linux-x86_64-appimage"],
        f"Ultraforce_{version}_amd64.deb": ["linux-x86_64-deb"],
        f"Ultraforce-{version}-1.x86_64.rpm": ["linux-x86_64-rpm"],
        f"Ultraforce_{version}_x64_en-US.msi": ["windows-x86_64", "windows-x86_64-msi"],
        f"Ultraforce_{version}_x64-setup.exe": ["windows-x86_64-nsis"],
    }
    prefix = f"https://github.com/{REPOSITORY}/releases/download/{tag}/"
    for name, keys in bundles.items():
        payload = assets[name]
        signature_asset = assets[name + ".sig"]
        if payload["browser_download_url"] != prefix + name or payload["size"] <= 0:
            raise ValueError("Invalid updater payload / 无效的更新载荷")
        raw = (signatures / (name + ".sig")).read_bytes()
        if signature_asset["digest"] != "sha256:" + hashlib.sha256(raw).hexdigest():
            raise ValueError("Signature asset digest mismatch / 签名产物摘要不一致")
        encoded = raw.decode("utf-8").strip()
        decoded = base64.b64decode(encoded, validate=True)
        if not decoded.startswith(b"untrusted comment:") or b"trusted comment:" not in decoded:
            raise ValueError("Malformed updater signature / 更新签名格式错误")
        # Signatures are generated by the trusted build jobs, not by this publisher. / 签名由可信构建任务生成，此发布器不生成签名。
        for key in keys:
            platforms[key] = {"signature": encoded, "url": payload["browser_download_url"]}
    return {
        "version": version,
        "notes": "",
        "pub_date": metadata["published_at"],
        "platforms": platforms,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, required=True)
    parser.add_argument("--signatures", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        metadata = json.loads(args.metadata.read_text(encoding="utf-8"))
        manifest = build_manifest(metadata, args.signatures)
        # Write only after every required platform has passed validation. / 所有必需平台验证通过后才写入。
        args.output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    except (KeyError, ValueError, TypeError, OSError) as error:
        print(f"Updater manifest rejected / 更新清单被拒绝: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    sys.exit(main())
