"""Regress the failed release envelope. / 回归发布正文结构失效问题。"""
import unittest
import json
from pathlib import Path
import subprocess
import sys
import tempfile

from check_release_pr_body import check_body


BODY = """A release update is ready for review.
发布更新已准备好，等待审查。
---

## [0.3.20](https://example.invalid/compare) (2026-10-21)

### Bug Fixes / 缺陷修复
* Preserve snapshots. / 保留快照。

### Upgrade note / 升级说明
Rebuild the verified cache. / 重建已验证缓存。

---
Generated by Release Please. / 由 Release Please 生成。
"""


class ReleaseBodyTest(unittest.TestCase):
    def test_ci_command_propagates_the_real_failure_as_a_nonzero_exit(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            body = root / "body.md"
            version = root / "version.json"
            version.write_text(json.dumps({".": "0.3.20"}), encoding="utf-8")
            for text, expected in ((BODY, 0), (BODY.replace("\n---\n", "\n"), 1)):
                body.write_text(text, encoding="utf-8")
                result = subprocess.run(
                    [sys.executable, str(Path(__file__).with_name("check_release_pr_body.py")),
                     "--body-file", str(body), "--version-file", str(version)],
                    capture_output=True, text=True,
                )
                self.assertEqual(result.returncode, expected, result.stdout + result.stderr)

    def test_generated_envelope_keeps_expanded_bilingual_upgrade_notes(self):
        check_body(BODY, "0.3.20")
        check_body(BODY.replace("\n", "\r\n"), "0.3.20")

    def test_rejects_the_missing_separators_that_skipped_publication(self):
        with self.assertRaisesRegex(ValueError, "separators"):
            check_body(BODY.replace("\n---\n", "\n"), "0.3.20")

    def test_rejects_a_partially_removed_envelope(self):
        with self.assertRaisesRegex(ValueError, "separators"):
            check_body(BODY.replace("\n---\n", "\n", 1), "0.3.20")

    def test_rejects_a_stale_release_version(self):
        with self.assertRaisesRegex(ValueError, "version"):
            check_body(BODY, "0.3.21")

    def test_rejects_notes_without_a_version_heading(self):
        with self.assertRaisesRegex(ValueError, "heading"):
            check_body(BODY.replace("## [0.3.20]", "Release [0.3.20]"), "0.3.20")

    def test_rejects_missing_generated_wrapper_text(self):
        for body in (BODY[BODY.index("---"):], BODY[:BODY.rindex("---") + 3]):
            with self.subTest(body=body):
                with self.assertRaisesRegex(ValueError, "header and footer"):
                    check_body(body, "0.3.20")

    def test_rejects_an_empty_release(self):
        with self.assertRaisesRegex(ValueError, "empty"):
            check_body("Header / 页首\n---\n## [0.3.20]\n---\nFooter / 页尾", "0.3.20")
